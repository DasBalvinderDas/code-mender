"""Tools that use the REAL CodeMender through the runner service (find -> verify -> fix)."""
from __future__ import annotations

import asyncio
import os
import tempfile

from google.adk.tools import ToolContext

from . import reports, runner_client
from .rules import RULES
from .scanner import SEV_ORDER, Finding, ScanResult
from .tools import PENDING_PDF_KEY, _STATE_KEY

RUN_KEY = "codemender_run_id"
_OWASP = {r.cwe: r.owasp for r in RULES} | {"CWE-22": "A01:2021 Broken Access Control"}
ENGINE = "CodeMender CLI (cm)"


def to_scan_result(run: dict) -> ScanResult:
    r = run["result"]
    findings = []
    for f in r["findings"]:
        ver, fix = f.get("verification") or {}, f.get("fix") or {}
        cwe = f.get("vuln_type") or ""
        status = f["status"]
        if status == "FIXED":
            how = "Patch generated by CodeMender" + (", build/test validation passed." if fix.get("build_validated") else ".")
        else:
            how = "Not yet fixed. Ask for a fix to run `cm fix` on this finding."
        evidence = (ver.get("report") or ver.get("plan") or "").strip()
        verification = (f"{status}. {evidence}" if evidence else
                        {"OPEN": "Not verified (no exploit was run for this finding).", "VERIFIED": "Exploit confirmed.", "FIXED": "Fix applied."}.get(status, status))
        findings.append(Finding(
            id=f["short_id"], rule_id=cwe or "CM", title=f["title"], severity=f["severity"] if f["severity"] in SEV_ORDER else "MEDIUM",
            cwe=cwe, owasp=_OWASP.get(cwe, ""), file=f["file"], line=int(f.get("start_line") or 0), snippet=(f.get("snippet") or "").strip()[:200],
            description=(f.get("analysis") or "").strip()[:1500], remediation=how, verification_plan=verification[:1200],
            confidence=str(f.get("confidence", "")), patch=fix.get("diff", ""), status=status.lower() if status else "detected"))
    res = ScanResult(r["repo"] + (f"/{r['subdir']}" if r.get("subdir") else ""), r.get("ref", ""), r.get("commit", ""),
                     r.get("files_scanned", 0), r.get("lines_scanned", 0), {}, findings, ENGINE)
    return res


async def run_codemender(repo_url: str, tool_context: ToolContext, ref: str = "", subdir: str = "", deep: bool = False,
                         verify_top: int = 2, fix_top: int = 1, install_deps: bool = False, context: str = "") -> dict:
    """Start a REAL CodeMender run on a GitHub repo: cm find, then exploit verification and validated fixes for the top findings.

    This takes many minutes (find ~1-10, each verify ~3, each fix ~5-7). It returns a run_id immediately;
    then call check_codemender_run to follow progress and get the PDF report.

    Args:
        repo_url: https://github.com/<owner>/<repo> (public, or private if the runner has a token).
        ref: Optional branch or tag.
        subdir: Optional folder inside the repo to scan.
        deep: Use `cm find --deep` for an exhaustive file-by-file scan (slower).
        verify_top: How many of the most severe findings to verify with a real exploit (0-10, default 2).
        fix_top: How many verified findings to fix and validate (0-5, default 1).
        install_deps: Install the repo's Python requirements before verification (runs repo install code; off by default).
        context: Optional project rules (like CONTEXT.md) passed to `cm fix -c` so patches follow team conventions.
    """
    if not runner_client.runner_url():
        return {"status": "error", "message": "The CodeMender runner is not configured (CODEMENDER_RUNNER_URL). "
                "Use analyze_repository for the built-in quick scan instead."}
    try:
        job = await runner_client.start({"repo_url": repo_url, "ref": ref, "subdir": subdir, "deep": deep, "verify_top": verify_top,
                                         "fix_top": fix_top, "install_deps": install_deps, "context": context})
    except Exception as exc:
        return {"status": "error", "message": str(exc)}
    tool_context.state[RUN_KEY] = job["id"]
    return {"status": "started", "run_id": job["id"],
            "note": "CodeMender is running in an isolated sandbox. Expect roughly 5-10 minutes for a small repo. "
                    "Call check_codemender_run to follow progress."}


async def check_codemender_run(tool_context: ToolContext, run_id: str = "", wait_seconds: int = 60) -> dict:
    """Check a CodeMender run. When it is complete, the PDF report is attached to the reply and findings are stored for follow-up questions.

    Args:
        run_id: The run id from run_codemender (defaults to the latest run in this conversation).
        wait_seconds: Wait up to this many seconds (max 240) for completion before returning progress.
    """
    run_id = run_id or tool_context.state.get(RUN_KEY, "")
    if not run_id:
        return {"status": "error", "message": "no CodeMender run found; start one with run_codemender"}
    deadline = asyncio.get_event_loop().time() + max(0, min(int(wait_seconds), 240))
    while True:
        try:
            run = await runner_client.get(run_id)
        except Exception as exc:
            return {"status": "error", "message": str(exc)}
        if run["status"] in ("completed", "failed") or asyncio.get_event_loop().time() >= deadline:
            break
        await asyncio.sleep(10)
    if run["status"] == "failed":
        return {"status": "failed", "message": run.get("error")}
    if run["status"] != "completed":
        return {"status": run["status"], "stage": run.get("stage"), "progress": run.get("progress", [])[-5:],
                "note": "Still running. Tell the user the current stage and offer to check again shortly."}
    res = to_scan_result(run)
    fd, pdf_path = tempfile.mkstemp(prefix="cm_report_", suffix=".pdf")
    with os.fdopen(fd, "wb") as fh:
        fh.write(await asyncio.to_thread(reports.to_pdf_bytes, res))
    tool_context.state[PENDING_PDF_KEY] = pdf_path
    tool_context.state[_STATE_KEY] = {"findings": [f.to_dict() for f in res.findings], "summary": reports.summary(res)}
    by_status = {}
    for f in res.findings:
        by_status[f.status.upper()] = by_status.get(f.status.upper(), 0) + 1
    top = [{"id": f.id, "severity": f.severity, "status": f.status.upper(), "title": f.title, "cwe": f.cwe, "file": f.file, "line": f.line,
            "has_patch": bool(f.patch)} for f in res.findings[:12]]
    return {"status": "completed", "engine": ENGINE, "summary": reports.summary(res), "by_status": by_status, "findings": top,
            "run_errors": run["result"].get("errors", []), "build_command": run["result"].get("build_command"),
            "report": "PDF report is attached to this reply (CodeMender_Security_Report.pdf)"}
